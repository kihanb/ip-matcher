def iana_to_windows_timezone(iana_tz: str, offset_sec: int = 0) -> str:
    """Resolve an IANA timezone name to an exact Windows timezone ID."""
    if iana_tz in IANA_TO_WINDOWS_TZ:
        return IANA_TO_WINDOWS_TZ[iana_tz]

    # Try computing standard UTC offset via zoneinfo if available
    if iana_tz:
        try:
            zi = ZoneInfo(iana_tz)
            # Pick Jan 15 (Northern standard / Southern summer) as baseline check
            dt = datetime(2026, 1, 15, 12, 0, tzinfo=timezone.utc).astimezone(zi)
            std_offset = int((dt.utcoffset() or timezone.utc.utcoffset(None)).total_seconds())  # type: ignore[arg-type]
            if std_offset in OFFSET_TO_WINDOWS_TZ:
                return OFFSET_TO_WINDOWS_TZ[std_offset]
        except Exception:
            pass

    if offset_sec in OFFSET_TO_WINDOWS_TZ:
        return OFFSET_TO_WINDOWS_TZ[offset_sec]

    # Nearest 30-min bucket
    nearest = min(OFFSET_TO_WINDOWS_TZ.keys(), key=lambda k: abs(k - offset_sec))
    return OFFSET_TO_WINDOWS_TZ[nearest]


def resolve_target_profile(ip_info: dict[str, Any]) -> dict[str, Any]:
    """
    Build the expected Windows configuration profile that matches the detected IP.
    """
    code = str(ip_info.get("country_code") or "").upper()
    iana_tz = str(ip_info.get("iana_timezone") or "")
    offset_sec = int(ip_info.get("utc_offset_sec") or 0)

    country = COUNTRY_PROFILES.get(code)
    if country:
        win_tz = (
            iana_to_windows_timezone(iana_tz, offset_sec)
            if iana_tz
            else country["default_tz"]
        )
        return {
            "country_code": code,
            "country_name": country["name"],
            "country_name_fa": country["name_fa"],
            "geo_id": country["geo_id"],
            "windows_tz": win_tz,
            "iana_timezone": iana_tz,
            "utc_offset_sec": offset_sec,
            "culture": country["culture"],
            "language_tag": country["language_tag"],
            "input_tip": country["input_tip"],
            "currency": ip_info.get("currency") or country["currency"],
            "city": ip_info.get("city") or "",
            "latitude": ip_info.get("latitude"),
            "longitude": ip_info.get("longitude"),
        }

    # Generic fallback for less common countries
    win_tz = iana_to_windows_timezone(iana_tz, offset_sec)
    fallback_culture = f"en-{code}" if code else "en-US"
    return {
        "country_code": code or "US",
        "country_name": ip_info.get("country_name") or code or "Unknown",
        "country_name_fa": ip_info.get("country_name") or code or "نامشخص",
        "geo_id": None,
        "windows_tz": win_tz,
        "iana_timezone": iana_tz,
        "utc_offset_sec": offset_sec,
        "culture": fallback_culture,
        "language_tag": "en-US",
        "input_tip": "0409:00000409",
        "currency": ip_info.get("currency") or "USD",
        "city": ip_info.get("city") or "",
        "latitude": ip_info.get("latitude"),
        "longitude": ip_info.get("longitude"),
    }
